/**
 * Get all emojis as a flat array
 */
export const getAllEmojis = (): string[] => {
  return EMOJI_CATEGORIES.flatMap(cat => cat.emojis)
}

/**
 * Search emojis by category name or emoji itself
 */
export const searchEmojis = (query: string): string[] => {
  if (!query) return getAllEmojis()
  const lowerQuery = query.toLowerCase()
  const results: string[] = []
  
  for (const category of EMOJI_CATEGORIES) {
    // Include all emojis from matching category
    if (category.name.toLowerCase().includes(lowerQuery) || 
        category.id.toLowerCase().includes(lowerQuery)) {
      results.push(...category.emojis)
    } else {
      // Otherwise filter individual emojis (basic matching)
      results.push(...category.emojis.filter(emoji => emoji.includes(query)))
    }
  }
  
  return [...new Set(results)]
}
