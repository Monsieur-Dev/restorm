import type {
  AdapterOptions,
  GenericOperationShape,
  ImportAdapter,
  NormalizedOperation,
  NormalizedSpec
} from './types'

/**
 * Postman collections are folders-of-folders-of-requests with no
 * dedicated schema / enum representation. The idempotent pipeline
 * only needs the operations dimension; models / enums stay empty so
 * the diff counters stay accurate (no spurious "X enums removed"
 * notifications when nothing's changed).
 *
 * `naturalKey` walks the folder path + request name + method so
 * renaming a request, or moving it between folders, registers as a
 * structural change rather than an in-place rename — which is the
 * conservative choice given Postman has no stable id beyond
 * `_postman_id` (often regenerated by tools).
 */
interface PostmanRequestLike {
  method?: string
  url?: { raw?: string } | string
}

interface PostmanItemLike {
  name?: string
  request?: PostmanRequestLike
  item?: PostmanItemLike[]
  _postman_id?: string
}

interface PostmanCollectionLike {
  info?: { name?: string; version?: string | { major?: number; minor?: number; patch?: number } }
  item?: PostmanItemLike[]
}

function postmanUrl(url: PostmanRequestLike['url']): string {
  if (typeof url === 'string') return url
  if (url && typeof url === 'object' && typeof url.raw === 'string') return url.raw
  return ''
}

function flattenItems(items: PostmanItemLike[], path: string[] = []): { item: PostmanItemLike; path: string[] }[] {
  const out: { item: PostmanItemLike; path: string[] }[] = []
  for (const item of items) {
    if (item.request) {
      out.push({ item, path })
      continue
    }
    if (item.item) {
      const childPath = item.name ? [...path, item.name] : path
      out.push(...flattenItems(item.item, childPath))
    }
  }
  return out
}

function readVersion(info: PostmanCollectionLike['info']): string | undefined {
  if (!info?.version) return undefined
  if (typeof info.version === 'string') return info.version
  const { major, minor, patch } = info.version
  if (major === undefined && minor === undefined && patch === undefined) return undefined
  return `${major ?? 0}.${minor ?? 0}.${patch ?? 0}`
}

export const postmanImportAdapter: ImportAdapter = {
  format: 'postman',
  extractNormalizedSpec(rawSpec: unknown, _options: AdapterOptions): NormalizedSpec {
    const spec = rawSpec as PostmanCollectionLike
    const flat = flattenItems(spec.item ?? [])
    const operations: NormalizedOperation[] = flat.map(({ item, path }) => {
      const method = (item.request?.method ?? 'GET').toUpperCase()
      const url = postmanUrl(item.request?.url)
      const naturalKey = `postman ${path.join('/')}::${method} ${item.name ?? url}`
      const shape: GenericOperationShape = {
        protocol: 'postman',
        raw: { method, url, name: item.name }
      }
      return {
        naturalKey,
        name: item.name ?? `${method} ${url}`,
        deprecated: false,
        shape,
        ...(item._postman_id !== undefined ? { operationId: item._postman_id } : {})
      }
    })
    return {
      ...(readVersion(spec.info) !== undefined ? { version: readVersion(spec.info) } : {}),
      operations,
      models: [],
      enums: [],
      environments: []
    }
  }
}
