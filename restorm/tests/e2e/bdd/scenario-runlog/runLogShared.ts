import { copyFileSync } from 'fs'
import { join, resolve } from 'path'
import { parse as yamlParse, stringify as yamlStringify } from 'yaml'
import { materializeSample, type StartedServices } from '../../helpers/testcontainers/services'

/** Reference fixture + its sidecars, committed under `tests/e2e/samples`. */
export const SAMPLES_DIR = resolve(__dirname, '../../samples')
export const REFERENCE_SAMPLE = join(SAMPLES_DIR, 'scenarios-e2e-reference-tests.restorm')
// The committed call-history zip (the runtime `.responses.zip` is gitignored).
export const REFERENCE_RESPONSES = join(SAMPLES_DIR, 'scenarios-e2e-reference-tests.restorm.responses-history.zip')
// Sidecar JSON the `Files` scenario reads by a RELATIVE path → must sit next to
// the working copy (the workspace dir).
export const REFERENCE_SIDECAR = join(SAMPLES_DIR, 'scenarios-e2e-reference-tests.pet-sample.json')

/** One golden per scenario, next to the sample (committed). Regenerate after an
 * intentional change with `UPDATE_RUNLOG_GOLDEN=1`. */
export function goldenPathFor(scenarioName: string): string {
  const slug = scenarioName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  return join(SAMPLES_DIR, `scenarios-e2e-reference-tests.${slug}-runlog.yaml`)
}

/** Copy the reference project + its call-history zip + the readFile sidecar into
 * `tempDir`, returning the working-copy `.restorm` path. The same layout the
 * interactive run-log e2e AND the headless CLI need. */
export function setupReferenceWorkingCopy(tempDir: string, services?: StartedServices): string {
  const workingCopy = join(tempDir, 'scenarios-e2e-reference-tests.restorm')
  if (services) materializeSample(REFERENCE_SAMPLE, workingCopy, services)
  else copyFileSync(REFERENCE_SAMPLE, workingCopy)
  copyFileSync(REFERENCE_RESPONSES, `${workingCopy}.responses.zip`)
  copyFileSync(REFERENCE_SIDECAR, join(tempDir, 'scenarios-e2e-reference-tests.pet-sample.json'))
  return workingCopy
}

/** Data keys whose value is an absolute wall-clock instant stamped per run —
 * placeholdered so the golden stays stable (config-embedded dates live under
 * OTHER keys and are left intact so real regressions surface). */
const DYNAMIC_TIME_KEYS = new Set([
  'timestamp', 'now', 'startedAt', 'finishedAt', 'endedAt', 'completedAt', 'durationMs', 'date'
])
/**
 * Header keys whose value is a credential and must never reach a committed
 * golden.
 *
 * `authorization` alone was sufficient while the run log only carried the
 * headers a transport reported back. It now also carries the request's **own
 * resolved** header rows — which is exactly where an API key under a
 * non-standard name lives. A golden is committed to git, and a key that lands
 * there is not undone by a later commit, so the set errs wide: a false mask
 * costs a less legible fixture, a missed one costs a leaked credential.
 */
const MASKED_VALUE_KEYS = new Set([
  'authorization',
  'proxy-authorization',
  'cookie',
  'set-cookie',
  'x-api-key',
  'apikey',
  'api-key',
  'x-auth-token',
  'x-access-token',
  'x-csrf-token',
  'x-amz-security-token',
  'private-token',
  'access-token'
])
/** A freshly-generated v4 UUID is non-deterministic → masked. */
const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i

/** A `$batch` multipart boundary is randomized per run — both the request
 * envelope (`batch_<rand>`, generated by the request serializer) and the mock
 * response envelope (`batchresponse_<rand>`, generated by the server). They show
 * up in `Content-Type` headers AND inside the (binary → base64) batch body, so
 * leaving them un-redacted makes the golden drift on every fresh run. Collapse
 * both to a stable token so the comparison is deterministic. The longer
 * `batchresponse_` is matched first so the shared `batch` prefix doesn't shadow
 * it. */
function redactBatchBoundaries(text: string): string {
  return text
    .replace(/batchresponse_[A-Za-z0-9_]+/g, 'batchresponse_<boundary>')
    .replace(/batch_[A-Za-z0-9_]+/g, 'batch_<boundary>')
}

/** A base64 string whose DECODED bytes are a multipart `$batch` envelope (the
 * binary-response branch base64-encodes `multipart/mixed` bodies). Heuristic:
 * decodable as base64 + the decoded text carries a multipart boundary marker. */
function decodeBatchBodyIfBase64(value: string): string | undefined {
  if (!/^[A-Za-z0-9+/]+=*$/.test(value) || value.length < 16) return undefined
  let decoded: string
  try {
    decoded = Buffer.from(value, 'base64').toString('utf-8')
  } catch {
    return undefined
  }
  return /--batch(response)?_/.test(decoded) ? decoded : undefined
}

/** The copied message is `<emoji> [<date>] <text>` — replace just the leading
 * date bracket so the run-time doesn't make the golden flaky. */
function normalizeMessage(message: string): string {
  return message.replace(/^(\S+ )\[[^\]]*\]/, '$1[<time>]')
}

function normalizeData(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(normalizeData)
  if (v !== null && typeof v === 'object') {
    const out: Record<string, unknown> = {}
    for (const [k, val] of Object.entries(v as Record<string, unknown>)) {
      if (DYNAMIC_TIME_KEYS.has(k)) out[k] = '<dynamic-time>'
      else if (MASKED_VALUE_KEYS.has(k.toLowerCase())) out[k] = '<masked>'
      else out[k] = normalizeData(val)
    }
    return out
  }
  if (typeof v === 'string') {
    if (UUID_V4.test(v)) return '<uuid>'
    // A base64-encoded multipart batch body: decode it so the golden is both
    // deterministic (random boundaries redacted) AND readable (the sub-response
    // HTTP envelopes are visible), rather than an opaque per-run-varying blob.
    const decodedBatch = decodeBatchBodyIfBase64(v)
    if (decodedBatch !== undefined) return redactBatchBoundaries(decodedBatch)
    // Plaintext occurrences (e.g. the `Content-Type: …; boundary=batch_<rand>`
    // header value) — redact the random boundary token in place.
    if (/batch(response)?_/.test(v)) return redactBatchBoundaries(v)
  }
  return v
}

/** Parse a copied/streamed run-log YAML, strip run-time noise, re-emit canonical
 * YAML. Both the live output and the golden go through this, so they compare
 * deterministically — used by the inspector copy e2e AND the headless CLI e2e.
 *
 * Local service PORTS are placeholdered on BOTH sides: the suites run their
 * mocks on ephemeral per-worker ports, while the committed goldens speak the
 * canonical compose ones. Host + path still assert; only the port token is
 * abstracted. */
export function normalizeRunLogYaml(raw: string): string {
  const portless = raw
    .replace(/localhost:\d+/g, 'localhost:<port>')
    .replace(/127\.0\.0\.1:\d+/g, '127.0.0.1:<port>')
  const entries = yamlParse(portless) as { message: string; data?: unknown }[]
  const normalized = entries.map((e) => {
    const message = normalizeMessage(e.message)
    return 'data' in e ? { message, data: normalizeData(e.data) } : { message }
  })
  return yamlStringify(normalized)
}
